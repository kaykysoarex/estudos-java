public class Main {

    public static void main(String[] args) {

        // 1. Crie uma variável chamada nome
        // Tipo: String
        // Valor: seu nome
        String nome = "Kayky";

        // 2. Crie uma variável chamada idade
        // Tipo: int
        // Valor: sua idade
        int idade = 21;

        // 3. Crie uma variável chamada altura
        // Tipo: double
        // Valor: sua altura
        double altura = 1.80;

        // 4. Crie uma variável chamada inicial
        // Tipo: char
        // Valor: primeira letra do seu nome
        char inicial = 'K';

        // 5. Crie uma variável chamada estudante
        // Tipo: boolean
        // Valor: true
        boolean estudante = true;

        // Depois mostre todas as variáveis na tela usando System.out.println()

        System.out.println(nome);
        System.out.println(idade);
        System.out.println(altura);
        System.out.println(inicial);
        System.out.println(estudante);
    }
}
