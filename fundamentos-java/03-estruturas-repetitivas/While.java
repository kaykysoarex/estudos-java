/* TEMA: WHILE. Use quando a quantidade não é conhecida. Estado inicial: numero=1; condição: <=5;
 * execução: imprime; atualização: ++; ao chegar a 6, termina. */
public class While { public static void main(String[] args) { int numero = 1;
    while (numero <= 5) { System.out.println(numero); numero++; }
} }
